/* Work order renderer: cover page + one page per item. Print CSS -> PDF. html2canvas -> PNGs. */
requireLogin();
const id = new URLSearchParams(location.search).get('id');
const $ = (i) => document.getElementById(i);

function esriExportUrl(items) {
  const lats = items.map(i => i.lat), lngs = items.map(i => i.lng);
  let minLat = Math.min(...lats), maxLat = Math.max(...lats);
  let minLng = Math.min(...lngs), maxLng = Math.max(...lngs);
  const padLat = Math.max((maxLat - minLat) * 0.25, 0.004);
  const padLng = Math.max((maxLng - minLng) * 0.25, 0.004);
  minLat -= padLat; maxLat += padLat; minLng -= padLng; maxLng += padLng;
  const url = `https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/export` +
    `?bbox=${minLng},${minLat},${maxLng},${maxLat}&bboxSR=4326&imageSR=4326&size=1200,800&format=jpg&f=image`;
  return { url, minLat, maxLat, minLng, maxLng };
}

function pinOverlay(item, bb) {
  const x = ((item.lng - bb.minLng) / (bb.maxLng - bb.minLng)) * 100;
  const y = (1 - (item.lat - bb.minLat) / (bb.maxLat - bb.minLat)) * 100;
  return `<div class="wo-pin" style="left:${x.toFixed(2)}%;top:${y.toFixed(2)}%">${item.pin_number}</div>`;
}

function header(title, date, page, total) {
  return `<div class="wo-header">
    <div class="wo-brand"><img src="/lot-dots-logo.jpg" alt="Lot Dots" class="wo-logo"></div>
    <div class="wo-title"><div class="t">${esc(title)}</div><div class="d">${esc(date)} · Page ${page} of ${total}</div></div>
  </div>`;
}
const footer = `<div class="wo-footer"><span>Generated by the Blossom Rock Crew App</span><span>Imagery © Esri</span></div>`;

async function boot() {
  if (!id) { $('msg').innerHTML = '<div class="error">No work order id.</div>'; return; }
  const { work_order: wo, items } = await api('/api/workorders/' + id);
  if (!items.length) { $('msg').innerHTML = '<div class="error">This work order has no items.</div>'; return; }
  const total = items.length + 1;
  const created = new Date(wo.created_at).toLocaleString(undefined, { dateStyle: 'long', timeStyle: 'short' });
  const bb = esriExportUrl(items);

  let html = `<div class="wo-page">
    ${header(esc(wo.title), created, 1, total)}
    <h2>${esc(wo.property_name)}</h2>
    <p class="hint">${items.length} work item${items.length === 1 ? '' : 's'} · Created by ${esc(wo.created_by_name || '—')}</p>
    <div class="wo-map"><img id="ovMap" crossorigin="anonymous" src="${bb.url}" alt="Work area map">${items.map(i => pinOverlay(i, bb)).join('')}</div>
    <h3 style="margin-top:18px">Work items</h3>
    <table class="plain"><tr><th>#</th><th>Category</th><th>Area</th><th>Status</th></tr>
    ${items.map(i => `<tr><td><strong>${i.pin_number}</strong></td><td>${esc(i.category)}</td><td>${esc(i.area || '—')}</td><td>${esc(i.status)}</td></tr>`).join('')}
    </table>${footer}</div>`;

  items.forEach((it, n) => {
    html += `<div class="wo-page">
      ${header(`Item #${it.pin_number} — ${esc(it.category)}`, created, n + 2, total)}
      <dl class="wo-kv">
        <dt>Area</dt><dd>${esc(it.area || '—')}</dd>
        <dt>Status</dt><dd>${esc(it.status)}${it.assigned_name ? ` (assigned to ${esc(it.assigned_name)})` : ''}</dd>
        <dt>Location</dt><dd>${it.lat.toFixed(5)}, ${it.lng.toFixed(5)}</dd>
        <dt>Notes</dt><dd>${esc(it.notes || '—')}</dd>
        <dt>Reported</dt><dd>${new Date(it.created_at).toLocaleString()}</dd>
        ${it.completed_at ? `<dt>Completed</dt><dd>${new Date(it.completed_at).toLocaleString()}</dd>` : ''}
      </dl>
      ${it.photo_path ? `<img class="wo-photo" crossorigin="anonymous" src="${esc(it.photo_path)}" alt="Item photo">` : '<p class="hint">No photo attached.</p>'}
      ${it.proof_photo_path ? `<h3>Completion proof</h3><img class="wo-photo" crossorigin="anonymous" src="${esc(it.proof_photo_path)}" alt="Completion photo">` : ''}
      ${footer}</div>`;
  });
  $('pages').innerHTML = html;

  $('printBtn').onclick = () => window.print();
  $('imgBtn').onclick = downloadImages;
}

async function downloadImages() {
  const hint = $('dlHint');
  if (typeof html2canvas === 'undefined') { hint.textContent = 'Image export library failed to load.'; return; }
  hint.textContent = 'Rendering pages…';
  try {
    const pages = [...document.querySelectorAll('.wo-page')];
    for (let n = 0; n < pages.length; n++) {
      const canvas = await html2canvas(pages[n], { scale: 2, useCORS: true, backgroundColor: '#ffffff' });
      const a = document.createElement('a');
      a.download = `work-order-${id}-page-${n + 1}.png`;
      a.href = canvas.toDataURL('image/png');
      a.click();
      hint.textContent = `Saved page ${n + 1} of ${pages.length}…`;
      await new Promise(r => setTimeout(r, 400));
    }
    hint.textContent = 'Done.';
  } catch (e) {
    hint.textContent = 'Image export hit a snag — use Print / Save as PDF instead.';
  }
}

boot().catch(e => { $('msg').innerHTML = `<div class="error">${esc(e.message)}</div>`; });
